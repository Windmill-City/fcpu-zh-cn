## SIMD инструкции
До сих пор вы можете управлять fCPU с помощью одной инструкции за игровой цикл и работать с парой сигналов на инструкцию.  
Но это не предел. fCPU поддерживает мнемонику _Single Instruction Multiple Data_, что означает, что вы можете делать гораздо более эффективную работу на одну инструкцию и, соответственно, на один игровой такт.  
SIMD-инструкции обрабатывают сразу несколько сигналов параллельно, в отличие от скалярных инструкций.  

При работе с SIMD-инструкциями необходимо учитывать следующие особенности:
- SIMD-инструкции не требуют дополнительных затрат времени на обработку, поэтому дружественные к UPS
- Некоторые векторные инструкции выполняются более 1 такта (`xmov mem1 red` требует 3 такта для заполнения канала `mem1` данными из провода `red` [item=red-wire])
- Извлечение эффективных данных из затронутой памяти возможно только после завершения выполнения векторной инструкции

**Легенда псевдокода**
- `dst()`, `src()`, и т.д.: неупорядоченная память (set/набор)
- `dst[]`, `src[]`, и т.д.: упорядоченная память (array/массив) *НЕ ПРИМЕНЯЕТСЯ ДО СИХ ПОР*.


