#### Блокировать выполнение до выполнения условия
Инструкции выполняют следующую за ними строку (в том же тике), как только выполняется условие.  
Это позволяет использовать их для копирования входного сигнала, вызвавшего продолжение.  

Например:
```
mov r1 0[virtual-signal=signal-green]
btrc r1
xmov m1 red
```

