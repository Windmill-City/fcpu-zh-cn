* Может управляться через специальные входные сигналы (прерывания)
* Один такт = одна инструкция (строчка) (кроме SIMD)
* Создано для гиков


## Описание
fCPU - это комбинатор, который включает в себя:

- Текст программы
- Набор регистров (для хранения сигналов или\и чисел)
- Несколько каналов памяти (для хранения ненулевых сигналов и чисел)
- Процессор (командный процессор и векторный сопроцессор)


### Программа
Программы для fCPU вводятся в виде обычного текста на упрощенном языке ассемблера (этого руководства достаточно для быстрого изучения) и состоят из строк.
Каждая строка представляет собой одну инструкцию.
Инструкция состоит из мнемоники и операндов.
Например: `mov out1 123[item=copper-ore]`, здесь mov - мнемоника,  out1 - первый операнд, 123[item=copper-ore] - второй операнд.
Эта инструкция указывает процессору послать сигнал [item=copper-ore] с номером 123 на провода ([item=red-wire]/[item=green-wire]), подключенные к выходу.

Мнемоники - это сокращенные названия операций, которые процессор понимает и знает, как их выполнять.
Операнды - это аргументы операций. Они используются для указания значений, над которыми будет выполняться операция.

В качестве операндов могут использоваться следующие значения:

- **Signal**/Сигнал: каждый сигнал состоит из типа и значения (`123[item=copper-ore]`)
  `123` - значение сигнала, представленное числом
  `[item=copper-ore]` - тип может быть представлен пиктограммой или текстом
- **Register**/Регистр: это специальная ячейка, которая хранит переданный сигнал неограниченное время (`reg1`, `r2`, ...)
- **Memory**/Канал памяти: один канал памяти состоит из нескольких ячеек (массивов), которые хранят сигнал неограниченное время (`mem1`, `m2`, ...)
- **LogNet**/Канал логистической сети: получает содержимое логистической сети, в которой размещен этот fCPU (`lgn[1]`, `lgn@2`, `logi[34]`, ...) ([item=roboport])
- **Input**/входной провод: вы можете принимать сигналы на провода, подключенные к входу комбинатора (`red`, `green`, `red1`, `green@3`, ...) ([item=red-wire]/[item=green-wire])
- **Output**/выходной провод: устанавливает значения на выходе комбинатора (`out1`, `out2`, ..., `out256`)
- **Address**: адрес инструкции (номер строки 34)
- **Label**/Маркировка в коде: записывается в виде текста с двоеточием перед ним (`:label`, `:anyname`, ...) (`anyname` - любое название)

Процессор выполняет инструкции из написанной программы по очереди, строка за строкой.


### Регистры

Имеется до 8 регистров чтения/записи общего назначения, названных **reg1**, ... **reg8** или сокращения **r1**, ... **r8**.  
Каждый регистр хранит тип сигнала и числовое значение (поддерживаются числа с плавающей точкой).  
Например, `mov reg2 10[item=iron-plate]`, эта инструкция присваивает **reg2** значение *10* и тип *[item=iron-plate]*.  

Кроме регистров общего назначения существуют регистры только для чтения:

- **ipt**: номер строки текущей инструкции.
- **clk**: тактовый генератор, значение увеличивается с каждым тиком.
- **cnr**, **cng**: номер сигнала на красном `cnr` [item=red-wire] или зеленом `cng` [item=green-wire] входном проводе.
- **cnl**: количество различных элементов в `lognet` ([item=roboport]), а не сумма их значений.
- **cnm1**, ..., **cnm4**: номер сигнала в памяти.

Выходные регистры (только запись):

- **out1**, ..., **out256**: выходные регистры (только целочисленные значения)


### Память

Для одновременной обработки нескольких сигналов в fCPU предусмотрен векторный сопроцессор, который обрабатывает SIMD-инструкции.  
В отличие от скалярных операций, которые обрабатывают ограниченное количество сигналов за один раз, векторные операции могут обрабатывать сотни сигналов за то же время.  
Память fCPU - это аналог регистров, но для векторных инструкций.  

Для использования доступны до 4 каналов памяти.  
Каждый канал состоит из нескольких ячеек памяти.  
В каждой ячейке хранится тип сигнала и числовое значение.  
Каналы памяти имеют адреса: `mem1`, ..., `mem4`.  
Для доступа к одной ячейке: `mem2[44]` или `mem1@3` (см. Массивы)


### Логистическая сеть (LogNet|[item=roboport])

Работает как единый канал памяти, за исключением того, что он доступен только для чтения и других очевидных ограничений. 
Данные канала `lgn` можно переместить (`xmov`) в обычный канал памяти для обработки.


## Массивы\косвенная адресация
К каждому регистру, каналу памяти или элементу логистической сети можно обращаться не только по прямому имени:
* **regN** (**reg1**, **r2**, и т.д... `N` - индекс регистра)
* **memC[M]** (**mem1[32]**, **m4[97]**, и т.д... `C` - номер канала памяти, `M` - индекс ячейки памяти)
* **lgn[I]** (**lgn[43]**, **logi[12]**, и т.д... `I` - индекс ячейки памяти)
Но также и с косвенным указателем:
* **reg@R** (**reg@3**, **r@7**, и т.д... `R` - индекс регистра)
* **memC@R** (**mem1@3**, **mem4@8**, и т.д... `R` - индекс регистра)
* **lgn@R** (**lgn@2**, **logi@8**, и т.д... `R` индекс регистра))

Это позволяет использовать их как индексы массива.  

Например:
```
mov r1 10[item=iron-plate]
mov r2 20[item=copper-plate]
mov r3 300[item=steel-plate]

mov r5 2
mov r6 r@5 # r6 будет равно r2, что равно 20[item=copper-plate]
mov r4 m1@5 # r4 будет равен mem1[2]

mov r5 3
mov r7 r@5 # r7 будет равен r3, что равно 300[item=steel-plate]
mov r4 m2@5 # r4 будет равен mem2[3]

mov r5 5
mov r8 r@5 # r8 будет равен r5, то есть 5
mov r4 m3@5 # r4 будет равен mem3[5]
```

Этот подход также можно использовать с `red` ([item=red-wire]), `green` ([item=green-wire]) входными проводами и каналами памяти, например: `red@1`, `green@8`, `mem1@3`.



## Управляющие сигналы, прерывания
Вы можете управлять состоянием fCPU по проводам ([item=red-wire]/[item=green-wire]), а не только вручную через игровой GUI.  
Для этого существуют некоторые сигналы:
* [virtual-signal=signal-fcpu-halt]: Остановить выполнение программы.
* [virtual-signal=signal-fcpu-run]: Продолжить выполнение программы.
* [virtual-signal=signal-fcpu-step]: Выполнить текущую инструкцию и перейти к следующей.
* [virtual-signal=signal-fcpu-sleep]: Засыпание заданных игровых тиков. В спящем режиме fCPU не обрабатывает прерывания.
* [virtual-signal=signal-fcpu-jump]: Перейти на указанную строку в программе.

Если fCPU встретит ошибку в программе, он выведет [virtual-signal=signal-fcpu-error] с номером строки в качестве значения.  


## Мнемоника

Инструкции, которые могут выполняться по очереди на каждый кадр.  
Каждая инструкция принимает один или несколько операндов и изменяет их или состояние fCPU.  

**Терминология**

* **V** `value`/**значение** : целочисленная константа в диапазоне [-2^31..2^31], (`-3500`)
* **T** `type`/**тип** : тип сигнала (`[item=iron-ore]`, `[item=copper-plate,quality=rare]`)
* **Q**, `quality`/**качество**: только сигнал качества (`'epic'`, `[quality=legendary]`) _WIP_
* **VT** `signal`/**сигнал** : состоит из **V**-значения и **T**-типа (`123[item=copper-ore]`, `456[item=iron-plate,quality=uncommon]`)
* **R** `register`/**регистр** : (`reg1`, `r3`, ..., `reg8` или `r@4` нотация, или одна ячейка памяти `m1[23]` или один входной проводной ([item=red-wire]/[item=green-wire]) сигнал `red34`, `green@3`)
* **M** `memory`/**память** : канал (`mem1`, `m2`, ..., `mem4`)
* **N** `lognet`/**логистическая сеть** : канал (`lgn`, `logi`, `lnc`) ([item=roboport])
* **I** `input`/**провод** : входной провод (`red`, `green`) ([item=red-wire]/[item=green-wire])
* **O** `output`/**провод** : выходной провод (`out1`, `out2`, ..., `out256`, `out`)

- **A** `address`/**адрес** : номер строки инструкции (5)
- **L** `label`/**метка** : метка инструкции (`:labelname`)
- **S** `string`/**строка** : используется в служебной мнемонике (`'rotation_speed'`)
- **src** - источник.
- **dst** - место назначения.

`...` - один или несколько, может быть указано несколько раз с разделителем/пробелом.  
`?` - необязательный, может быть указан.

