## Возможности

* Поддерживает чертежи
* Поддерживает копирование и вставку
* Поддерживает мультиплеер
* Поддерживает качество
* Поддерживает внутриигровые вики [Informatron](https://mods.factorio.com/mod/informatron) и [Booktorio](https://mods.factorio.com/mod/Booktorio)
* Внутриигровой отладчик с точками остановки
* 256 инструкций для всей программы
* До 64 регистров общего назначения
* До 4 канала памяти для векторной обработки
* Интегрированный доступ к логистической сети
* 50+ опкодов
* Богатые математические инструкции, тригонометрия, округление
* SIMD-инструкции, `min`, `max`, фильтр, сравнение и т.д.
* Два входных провода ([item=red-wire] **красный**, [item=green-wire] **зеленый**)
* два выходных провода ([item=red-wire] **красный**, [item=green-wire] **зеленый**) имеют одинаковые выходные сигналы и значения
