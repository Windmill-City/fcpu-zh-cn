## SIMD память (объяснение)
Я попытаюсь объяснить, как мод работает с памятью и почему это сделано именно так.  

Каждый провод ([item=red-wire]/[item=green-wire]) Factorio может содержать огромное количество сигналов одновременно (сотни). Эти сигналы никак не отсортированы и фактически имеют случайные индексы. Чтобы все выглядело более красиво, панели GUI сортируют сигналы в порядке убывания (столбы электропередач и ⓘ всплывающие подсказки).  

Для обработки большого количества сигналов в игре используются ванильные комбинаторы, оптимизированные внутри самой игры на C++. Если вы попытаетесь обработать аналогичное количество сигналов в LUA-моде, возникнут значительные накладные расходы и падение производительности. Это относится к любому моду Factorio.  

Чтобы обойти это, fCPU использует трюк - он частично компилирует написанную программу (SIMD-мнемоники `x*`) в невидимые схемы с ванильными комбинаторами и координирует их выполнение построчно. Эта часть fCPU называется сопроцессором. Она обеспечивает более высокую производительность, чем аналогичные вычисления на LUA.  

В отличие от регистров, которые реализуются как обычные переменные и всегда сохраняют свои индексы, память для SIMD-команд также реализуется с помощью ванильных комбинаторов.  

А вот и самое главное: 
Чтобы изменить память, вам нужно вычесть старое значение и добавить новое для того же типа сигнала.
Как и любая другая операция комбинатора, это нарушает индексы сигналов.


