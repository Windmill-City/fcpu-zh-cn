# 简介

程控运算器由以下几部分组成：

* 程序代码
* 一组寄存器（用来存放信号和数值）
* 4 个内存通道（用来存放信号和数值）
* 指令处理器
* 向量协处理器


## 程序

程序用简化的汇编语言编写（读完本说明即可快速上手），由若干行组成，一行一条指令。

每条指令由「助记符」和「操作数」组成。例如：

```
mov out1 123[item=copper-ore]
```

* `mov`：助记符，表示这条指令要做什么
* `out1`：操作数 1
* `123[item=copper-ore]`：操作数 2

这条指令的意思是：把「数值 123、类型为铜矿」的信号发送到输出端口。

「助记符」是处理器认识的运算名称的缩写；「操作数」是运算的对象，用来指明参与运算的值。

程序运行时，处理器会从上到下逐行执行指令。

可以作为操作数的内容：

* **信号**：由类型和数值组成，如 `123[item=copper-ore]`
* **寄存器**：能长期存放信号的单元，如 `reg1`、`r2`
* **局部变量**：函数调用过程中临时存放信号的单元，如 `var1`、`v2`
* **内存通道**：由多个单元格组成、能长期存放信号的数组，如 `mem1`、`m2`
* **物流网络**：读取本运算器所在物流网络的内容，如 `lgn[1]`、`lgn@2`、`logi[34]`
* **输入端口**：读取接在运算器输入端的信号，如 `red`、`green`、`red1`、`green@3`
* **输出端口**：设置运算器输出端的信号，如 `out1`、`out2`、...、`out256`
* **地址**：指令行号，如 `34`
* **标签**：以冒号开头的代码记号，如 `:label`、`:anyname`


## 寄存器

有 8 个通用寄存器：**reg1** ～ **reg8**（简称 **r1** ～ **r8**）。
每个寄存器存放一个信号，包括类型和数值（支持浮点数）。

例如：

```
mov reg2 10[item=iron-plate]
```

这条指令把 **reg2** 的数值设为 *10*，类型设为 *[item=iron-plate]*。

除了通用寄存器，还有一些只读寄存器：

* **ipt**：程序计数器，当前正在执行的指令行号
* **clk**：时钟，每过一个 tick 加 1
* **cnr**：红色输入端口上的信号种数
* **cng**：绿色输入端口上的信号种数
* **cnl**：物流网络中不同物品的种数（不是数值总和）
* **cnm1** ～ **cnm4**：各内存通道中的信号种数
* **sp**：栈指针
* **bp**：基址指针

输出寄存器（只写）：

* **out1** ～ **out256**：输出寄存器。只接受带类型的整数值；没有类型、或数值为零的信号都会被丢弃。


## 输入端口与输出端口

程控运算器有红、绿两个输入端口，以及红、绿两个输出端口（两条输出线上的信号完全相同，接哪条都可以）。

**读取输入（只读）**

输入端口只能读，不能写。有三种读法：

- 按类型读取。指定一个信号类型，从整条输入线上取它的数值（推荐，最常用）：

```
fid r1 red [item=iron-ore]    ; 取红线上铁板的数量，存入 r1
fir r2 [item=copper-plate]        ; fir 是 fid ... red ... 的简写
fig r3 [item=iron-ore]        ; fig 是 fid ... green ... 的简写
```

- 按下标读取。`red`、`green` 后直接跟数字，表示取该线上第几个信号（类型和数值一起读出）；数字也可由寄存器提供（`@` 间接寻址）：

```
mov r1 red1       ; 红线上第 1 个信号
mov r2 green@3    ; 绿线上第 r3 个信号（r3 里存的是下标）
mov r4 red34      ; 红线上第 34 个信号
```

注意：线缆上信号的顺序是随机的，下标会随线缆内容变化；想确定某个信号在什么位置，可用 `idx` 指令查询。

- 把整条输入线当作一个通道，交给 SIMD 指令整体处理：

```
xmov m1 red       ; 把整条红线复制进内存通道 m1
xuni m2 red green ; 把红、绿两条输入合并进 m2
```

想知道线上有几个信号，读只读寄存器 `cnr`（红）和 `cng`（绿）。

**写到输出（只写）**

输出端口用于把信号发出去，只能写。写入输出寄存器后，信号会同时出现在红、绿两条输出线上：

```
mov out1 123[item=copper-ore]  ; 输出 123 个铜矿
ssv out2 5                     ; 只改数值，输出数值 5
sst out3 [item=iron-plate]     ; 只改类型
clr out                        ; 清空所有输出
```

输出寄存器用数字编号，编号也可以由寄存器提供（`out@4` 表示把第 r4 个输出寄存器作为目标）。旧式写法 `out`（不带数字）已废弃，等价于 `out1`。

输出寄存器只接受带类型的整数值，数值为零或没有类型的信号会被丢弃。


## 栈

栈在内存中**向下增长**（从高地址到低地址）。

* 类型：LIFO（后进先出）
* 大小：4096

想知道栈还剩多少空间？读 `sp` 寄存器即可：`mov r1 sp`。

用 `push` 和 `pop` 指令压栈、弹栈：

```
push r1 r2 r3
```

等价于：

```
push r1
push r2
push r3
```


## 函数

通过 `call`、`ret`、`enter`、`leave` 四条指令实现函数调用，语义与 x86 汇编很接近。

`bp` 保存当前函数栈帧的起始地址，通过它就能访问局部变量。

`call 地址 偏移?`：先把返回地址（当前指令行号）压入栈，再跳转到指定地址或标签。支持嵌套调用和递归。
等价于：

```
push ipt
jmp 地址 偏移
```

`ret`：从栈中弹出返回地址，跳回该处继续执行，从而结束当前函数。
等价于：

```
pop 临时
jmp 临时
```

`enter 数量`：为函数建立新的栈帧。先把当前基址指针压入栈，再设置新的基址指针，并可为局部变量预留空间。
等价于：

```
push bp        ; 保存上一个基址指针 bp
mov  bp, sp    ; 把新栈帧的基址设为当前栈指针
sub  sp, 数量  ; 为局部变量分配空间
```

`leave`：撤销 `enter` 的操作。先丢弃局部变量，再恢复上一个基址指针，在返回前清除当前栈帧。
等价于：

```
mov  sp, bp    ; 丢弃局部变量
pop  bp        ; 恢复上一个基址指针 bp
```

几次函数调用之后的栈示意图：

```
4096
| ...         |
| older  ipt  | call :fn1
|             | enter 3
| old    bp   |
|        var1 | <-- old bp - 1
| ...         |
|        var3 | <-- old bp - 3
| ...         |
| old    ipt  | call :fnN
|             | enter 1
| actual bp   | <-- bp
|        var1 | <-- bp - 1
|             | <-- sp
| ...         |
1
```


## 局部变量

局部变量存放在栈顶，执行 `leave` 之后就不能再访问。

想为变量建立函数栈帧，用 `enter 数量`。例如：

```
enter 3
  mov var1 1
  mov var2 2
  mov var3 3
  mov r4 v1
  mov r5 v2
  mov r6 v3
leave
```


## 内存单元

为了能同时处理多个信号，程控运算器配有专门执行 SIMD 指令的向量协处理器。

标量指令一次只能处理一个信号，而向量指令能在同样的时间内处理成百上千个信号。

内存单元的作用和寄存器类似，但它是给向量指令用的。

一共有 4 个内存通道：`mem1`、`mem2`、`mem3`、`mem4`。
每个通道由多个单元格组成，每个单元格存放一个信号（类型 + 数值）。
访问单个单元格：`mem2[44]` 或 `mem1@3`（详见「数组与间接寻址」）。


## 物流网络

物流网络相当于一个额外的内存通道，区别在于它是只读的。

可以用 `xmov` 把 `lgn` 通道搬进内存通道，再进行操作。


# 数组与间接寻址

每个寄存器、内存通道或物流网络除了用名称直接寻址外，还可以把寄存器里的数值当作下标，进行间接寻址。

直接寻址：
* 寄存器：**reg1**、**r2**
* 内存单元：**mem1[32]**、**m4[97]**
* 物流网络：**lgn[43]**、**logi[12]**

间接寻址（用 `@`，下标存放在寄存器里）：
* 寄存器：**reg@3**、**r@7**
* 内存单元：**mem1@3**、**mem4@8**
* 物流网络：**lgn@2**、**logi@8**

也就是说，可以把寄存器中的值当作**数组**下标来用。例如：

```
mov r1 10[item=iron-plate]
mov r2 20[item=copper-plate]
mov r3 300[item=steel-plate]

mov r5 2
mov r6 r@5   ; r6 等于 r2，即 20[item=copper-plate]
mov r4 m1@5  ; r4 等于 mem1[2]

mov r5 3
mov r7 r@5   ; r7 等于 r3，即 300[item=steel-plate]
mov r4 m2@5  ; r4 等于 mem2[3]

mov r5 5
mov r8 r@5   ; r8 等于 r5，即 5
mov r4 m3@5  ; r4 等于 mem3[5]
```

同样的方法也适用于 `red`、`green` 输入端口和内存单元，例如：`red@1`、`green@8`、`mem1@3`。


# 控制信号与中断

除了用游戏内的界面手动控制，还可以用输入信号来控制程控运算器，这就是「中断」：程序运行期间，外部随时可以用信号打断它，命令它暂停、继续、单步、休眠或跳转。

中断的工作方式：

* 中断信号是一组特殊的虚拟信号（见下面列表），通过输入端口（红、绿任意一条线）送入
* 每个 tick 在执行指令之前，处理器都会先检查输入上有哪些中断信号；信号数值大于 0 就触发对应的动作
* 中断由处理器本身处理，程序代码无法拦截；唯一例外是休眠期间，此时暂停/继续/单步/休眠信号都不生效，但跳转信号依然生效
* 中断信号的数值就是它的参数：休眠信号的值 = 需要休眠的 tick 数，跳转信号的值 = 要跳到的行号，其余信号只需要数值大于 0
* 如果同一tick出现多个中断信号，按优先级处理：程序运行时，暂停信号优先于休眠信号（同时出现时只暂停、不会进入休眠）；程序暂停时，继续信号优先于单步信号；跳转信号独立生效——只要数值大于 0 就总会跳转到指定行，与其它信号互不干扰（例如同时收到暂停与跳转信号，最终效果是程序暂停、程序计数器停在跳转目标那一行）

控制信号列表（按优先级从高到低排列）：

* `[virtual-signal=signal-fcpu-jump]`：跳到「该信号数值」指定的行（任意状态下都生效，优先级最高，与其它信号同时出现时也照常执行）
* `[virtual-signal=signal-fcpu-halt]`：暂停程序执行（程序运行时生效；与休眠信号同时出现时优先）
* `[virtual-signal=signal-fcpu-sleep]`：休眠「该信号数值」个 tick，休眠期间只处理跳转信号（程序运行时生效；与暂停信号同时出现时不生效）
* `[virtual-signal=signal-fcpu-run]`：继续运行（程序暂停时生效；与单步信号同时出现时优先）
* `[virtual-signal=signal-fcpu-step]`：单步，执行当前指令后停下（程序暂停时生效；与继续信号同时出现时不生效）

如果程序运行出错，程控运算器会输出 `[virtual-signal=signal-fcpu-error]` 信号，其数值就是出错的行号。


# 指令

指令按 tick 逐条执行，每条指令接受一个或多个操作数，并修改这些操作数或运算器的状态。

先说明操作数类型。后面每条指令的语法中都会用到这些词，方括号里表示允许的类型：

* **数值**：整数常量，取值在 `[-2^31, 2^31)` 范围内
  例：`-3500`
* **类型**：信号类型，可附带品质
  例：`[item=iron-ore]`、`[item=copper-plate,quality=rare]`
* **品质**：只表示品质
  例：`'epic'`、`[quality=legendary]`（暂未完成）
* **信号**：数值 + 类型（可带品质）
  例：`123[item=copper-ore]`、`456[item=iron-plate,quality=uncommon]`
* **引用**：寄存器、内存单元格、局部变量或输入信号
  例：`reg1`、`r3`、`r@4`、`m1[23]`、`red34`、`green@3`、`var1`、`v2`
* **内存**：内存通道（整个通道）
  例：`mem1`、`m2`、`mem4`
* **物流**：物流网络通道
  例：`lgn`、`logi`
* **输入**：输入端口
  例：`red`、`green`
* **输出**：输出端口
  例：`out1`、`out2`、...、`out256`
* **地址**：指令行号
  例：`5`
* **标签**：指令标签
  例：`:labelname`
* **字符串**：文本，如 `ugpf` 中的字段名
  例：`'rotation_speed'`

另外还有两个记号：

* **…**：这一项可以重复写多个，彼此用空格分隔
* **?**：这一项可以省略


## 常用

`nop`
空操作，什么都不做。

`clr`
清除所有寄存器、内存通道和输出。

`clr reg`
清除所有寄存器。

`clr out`
清除所有输出。

`clr mem`
清除所有内存通道。

`clr 目标…[引用/内存/输出]`
清除指定的寄存器、内存通道或输出端口。
例：`clr mem3 r2 out4`

`mov 目标…[引用/输出] 源[数值/类型/信号/引用]`
把「源」的信号（数值和类型）复制到「目标」，可以一次写多个目标。
目标 = 源
例：`mov out1 123[item=copper-ore]` 输出 123 个铜矿。

`ssv 目标…[引用/输出] 值[数值/引用]`
只把「目标」的数值改成「值」，类型不变。
目标 = 值

`sst 目标…[引用/输出] 类型[类型/引用]`
只把「目标」的类型改成「类型」，数值不变。
目标 = 类型

`ssq 目标…[引用/输出] 品质[类型/品质/引用]`
把「目标」的品质改成「品质」。
目标 = 品质

`fid 目标[引用/输出] 源[输入/内存] 类型[类型/引用]`
在「源」（红/绿输入端口或内存通道）中查找指定「类型」的信号：找到就把它的数值和类型写入「目标」，找不到则清空「目标」。

`idx 目标[引用] 源[输入/内存] 类型[类型/引用]`
在「源」中查找指定「类型」的信号，把它的位置序号写入「目标」。

`fir 目标[引用/输出] 类型[类型/引用]`
`fig 目标[引用/输出] 类型[类型/引用]`
分别是 `fid ... red ...` 和 `fid ... green ...` 的简写，只在红色 / 绿色输入端口上查找。


## 品质

品质等级与数字的对应关系参见 https://lua-api.factorio.com/latest/prototypes/QualityPrototype.html#level

`qn 目标[引用/输出] 类型[类型/引用/输入]`
把「类型」的品质等级换算成数字写入「目标」（普通=0、罕见=1、稀有=2、史诗=3、传奇=5）。


## 交换

`swp a[引用] b[引用]`
交换两个寄存器或内存单元格中的完整信号。

`swpt a[引用] b[引用]`
只交换两个信号的类型。

`swpv a[引用] b[引用]`
只交换两个信号的数值。

`swpq a[引用] b[引用]`
只交换两个信号的品质。


## 算术

算术指令写成 `add 目标 源? 值` 的格式：不写「源」时按「目标 = 目标 运算符 值」计算；写了「源」时按「目标 = 源 运算符 值」计算。

`add 目标[引用] 源?[数值/引用] 值[数值/引用]`
加法。`目标 = 源 + 值`（不写「源」时 `目标 = 目标 + 值`）

`sub 目标[引用] 源?[数值/引用] 值[数值/引用]`
减法。`目标 = 源 - 值`（不写「源」时 `目标 = 目标 - 值`）

`mul 目标[引用] 源?[数值/引用] 值[数值/引用]`
乘法。`目标 = 源 * 值`（不写「源」时 `目标 = 目标 * 值`）

`div 目标[引用] 源?[数值/引用] 值[数值/引用]`
除法。`目标 = 源 / 值`（不写「源」时 `目标 = 目标 / 值`）

`mod 目标[引用] 源?[数值/引用] 值[数值/引用]`
取余。`目标 = 源 % 值`（不写「源」时 `目标 = 目标 % 值`）

`pow 目标[引用] 源?[数值/引用] 值[数值/引用]`
乘方。`目标 = 源 ^ 值`（不写「源」时 `目标 = 目标 ^ 值`）

`inc 目标[引用]`
自增。`目标 = 目标 + 1`

`dec 目标[引用]`
自减。`目标 = 目标 - 1`

反运算（操作数顺序反过来，方便表达「常数 - 变量」这类式子）：

`subi 目标[引用] 值[数值/引用]`
`目标 = 值 - 目标`

`divi 目标[引用] 值[数值/引用]`
`目标 = 值 / 目标`

`modi 目标[引用] 值[数值/引用]`
`目标 = 值 % 目标`

`powi 目标[引用] 值[数值/引用]`
`目标 = 值 ^ 目标`

`rnd 目标[引用] 最小值[数值/引用] 最大值[数值/引用]`
在 [`最小值`, `最大值`]（含端点）之间生成一个伪随机数，写入「目标」。

取整：

`fract 目标[引用]`
取「目标」数值的小数部分。

`floor 目标[引用]`
向下取整，取不大于「目标」数值的最大整数。

`round 目标[引用]`
四舍五入，取最接近「目标」数值的整数。

`ceil 目标[引用]`
向上取整，取不小于「目标」数值的最小整数。

位数操作：

`dig 目标[引用] 位数[数值/引用]`
取出「目标」数值中第「位数」位上的数字，写回「目标」。
`目标 = 目标 / 10^位数 % 10`

`dis 目标[引用] 位数[数值/引用] 值[数值/引用]`
把「目标」数值中第「位数」位改成「值」。
