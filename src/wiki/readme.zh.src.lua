# 流程控制

`lea 目标[引用/输出] 标签[标签]`
把「标签」对应的行号写入「目标」，之后可以用它做间接跳转。

`jmp 地址[数值/地址/标签/引用]`
跳转到指定地址或标签。

`jmp 地址[数值/地址/标签/引用] 偏移[数值/引用]`
跳转到「地址 + 偏移」或「标签 + 偏移」。
例：`jmp ipt -2` 跳回当前指令前两行（`ipt` 就是当前指令的行号）。

`hlt`
暂停程序执行，直到玩家手动恢复，或任一输入端口出现 Run 信号。

`slp 次数[数值/引用]`
休眠指定的 tick 数。休眠期间暂停/继续/单步等中断信号不生效，但跳转信号仍然生效。

`call 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
先把当前指令行号（返回地址）压入栈，再跳转到「地址 + 偏移」或「标签 + 偏移」。用于调用函数，支持嵌套和递归。
等价于：

```
push ipt
jmp 地址 偏移
```

`ret`
从栈中弹出地址并跳转过去，结束当前函数。
等价于：

```
pop 临时
jmp 临时
```

`enter 数量[数值]`
为局部变量在栈上预留空间。

`leave`
丢弃栈上的局部变量。


## 阻塞

阻塞指令会停下程序，直到条件满足为止。
条件满足的那一 tick，紧跟其后的下一条指令会立即执行，因此可以趁热把触发继续执行的输入信号原样取出来。

例如，等红线上的信号发生变化后，马上把整条红线复制进内存通道 m1：

```
mov r1 0[virtual-signal=signal-green]
btrc r1
xmov m1 red
```

`bkr 数量[数值/引用]`
`bkg 数量[数值/引用]`
`bkl 数量[数值/引用]`
阻塞，直到红色 / 绿色输入端口或物流网络上至少有「数量」个信号。

`btr 类型[类型/引用]`
`btg 类型[类型/引用]`
`bti 类型[类型/引用]`
`btl 类型[类型/引用]`
阻塞，直到红色 / 绿色 / 红绿合并 / 物流网络上出现指定「类型」的信号。
（`bti` 会把红、绿两条输入线合并起来检查。）

`btrc 寄存器[引用]`
`btgc 寄存器[引用]`
`btic 寄存器[引用]`
`btlc 寄存器[引用]`
阻塞，直到「寄存器」中的信号与红色 / 绿色 / 红绿合并 / 物流网络上对应信号不再相同；一旦线上信号发生变化，就把新值写回「寄存器」并继续执行。


## 比较

比较指令先检查条件：成立就继续执行下一条指令，不成立则跳过下一条。配合 `jmp :标签` 即可实现分支。

例：让 r1 从 0 数到 10：

```
clr
:counter
inc r1
tlt r1 10
jmp :counter
; 到这里时 r1 等于 10
```

`teq a[数值/字符串/引用] b[数值/字符串/引用]`
相等。`a == b`

`tne a[数值/字符串/引用] b[数值/字符串/引用]`
不相等。`a != b`

`tgt a[数值/字符串/引用] b[数值/字符串/引用]`
大于。`a > b`

`tlt a[数值/字符串/引用] b[数值/字符串/引用]`
小于。`a < b`

`tge a[数值/字符串/引用] b[数值/字符串/引用]`
大于或等于。`a >= b`

`tle a[数值/字符串/引用] b[数值/字符串/引用]`
小于或等于。`a <= b`

类型比较：

`tas a[类型/引用] b[类型/引用]`
两个信号的类型相同则继续，否则跳过下一条。

`tad a[类型/引用] b[类型/引用]`
两个信号的类型不同则继续，否则跳过下一条。


## 分支

分支指令 = 先比较，成立就直接跳转。名字与比较指令一一对应，把 `t` 换成 `b`，再多一个跳转地址参数。

例：

```
clr
:counter
inc r1
blt r1 10 :counter
; 到这里时 r1 等于 10
```

`beq a[数值/字符串/引用] b[数值/字符串/引用] 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
相等就跳转。若 `a == b`，执行 `jmp 地址 偏移`。

`bne a[数值/字符串/引用] b[数值/字符串/引用] 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
不相等就跳转。若 `a != b`，执行 `jmp 地址 偏移`。

`bgt a[数值/字符串/引用] b[数值/字符串/引用] 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
大于就跳转。若 `a > b`，执行 `jmp 地址 偏移`。

`blt a[数值/字符串/引用] b[数值/字符串/引用] 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
小于就跳转。若 `a < b`，执行 `jmp 地址 偏移`。

`bge a[数值/字符串/引用] b[数值/字符串/引用] 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
大于或等于就跳转。若 `a >= b`，执行 `jmp 地址 偏移`。

`ble a[数值/字符串/引用] b[数值/字符串/引用] 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
小于或等于就跳转。若 `a <= b`，执行 `jmp 地址 偏移`。

`bas a[类型/引用] b[类型/引用] 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
类型相同时跳转。

`bad a[类型/引用] b[类型/引用] 地址[数值/地址/标签/引用] 偏移?[数值/引用]`
类型不同时跳转。


# 其他指令

`ugpf 目标[引用] 名称[类型/引用] 字段[字符串]`
*Utility Get Prototype Field（读取原型字段）*
按「名称」查找原型（Prototype），把「字段」的值写入「目标」（只支持数字字段）。
该指令会依次在以下原型中查找字段：
1. https://lua-api.factorio.com/latest/LuaItemPrototype.html
2. https://lua-api.factorio.com/latest/LuaEntityPrototype.html

例：

```
ugpf r1 [item=inserter] 'inserter_stack_size_bonus'
