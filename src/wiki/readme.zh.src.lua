```


# SIMD 指令

到目前为止，我们每个 tick 只能执行一条指令，每条指令只能处理少量信号——但这远远不是上限。
程控运算器支持*单指令多数据*（SIMD）指令：一条指令（也就是一个 tick）就能完成更多计算。与标量指令一次只处理一个信号不同，SIMD 指令会一次并行处理多个信号。

使用 SIMD 指令时要注意：

* SIMD 指令本身不额外占用处理时间，对 UPS 友好
* 部分向量指令需要多个 tick 才能执行完（例如 `xmov mem1 red` 需要 3 个 tick 才能把红线的数据全部载入 `mem1`）
* 只有等向量指令执行完毕后，才能从受影响的内存中读到有效数据

伪代码图例：
* `dst()`、`src()`：无序内存（集合）
* `dst[]`、`src[]`：有序内存（数组）*尚未实现*


## SIMD 常用

`xmov 目标[内存/输出] 源[输入/内存/物流]`
把「源」通道（`each`）整体复制到「目标」。
`目标(each) = 源(each)`
例：`xmov m1 red` 把整条红线载入内存通道 m1。

`emit 目标[内存] 值…[数值/类型/信号/引用]`
把各个「值」追加到「目标」内存通道末尾（v0.5.0 之前顺序随机）。

`xuni 目标[内存/输出] a[输入/内存/物流] b[输入/内存/物流]`
把两个通道合并为一个。
`目标(each) = a(each) + b(each)`

`xflt 目标[内存/输出] 源?[输入/内存/物流] 掩码[输入/内存/物流]`
把「源」中所有与「掩码」白名单匹配的信号复制到「目标」。
*内部设计由 [Halke1986](https://www.reddit.com/user/Halke1986/) 提供*

SIMD 算术指令和标量算术写法一致：不写「源」时按「目标 = 目标 op 值」计算，写了「源」时按「目标 = 源 op 值」计算。

`xadd 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用/输入/内存]`
加法。`目标(each) = 源(each) + 值`（不写「源」时 `目标(each) = 目标(each) + 值`）

`xsub 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用/输入/内存]`
减法。`目标(each) = 源(each) - 值`（不写「源」时 `目标(each) = 目标(each) - 值`）

`xmul 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用/输入/内存]`
乘法。`目标(each) = 源(each) * 值`（不写「源」时 `目标(each) = 目标(each) * 值`）

`xdiv 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用/输入/内存]`
除法。`目标(each) = 源(each) / 值`（不写「源」时 `目标(each) = 目标(each) / 值`）

`xmod 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用/输入/内存]`
取余。`目标(each) = 源(each) % 值`（不写「源」时 `目标(each) = 目标(each) % 值`）

`xpow 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用/输入/内存]`
乘方。`目标(each) = 源(each) ^ 值`（不写「源」时 `目标(each) = 目标(each) ^ 值`）


## SIMD 比较

把「源」中每个信号的值与「值」比较，满足条件的信号才会写入「目标」。
只写两个操作数时，「源」就是「目标」。

`xceq 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
相等。若 `源(each) == 值`，则 `目标(each) = 源(each)`

`xcne 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
不相等。若 `源(each) != 值`，则 `目标(each) = 源(each)`

`xcgt 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
大于。若 `源(each) > 值`，则 `目标(each) = 源(each)`

`xclt 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
小于。若 `源(each) < 值`，则 `目标(each) = 源(each)`

`xcge 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
大于或等于。若 `源(each) >= 值`，则 `目标(each) = 源(each)`

`xcle 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
小于或等于。若 `源(each) <= 值`，则 `目标(each) = 源(each)`


## SIMD 位运算

`xand 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
按位与（AND）。`目标(each) = 源(each) & 值`（不写「源」时 `目标(each) = 目标(each) & 值`）

`xor 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
按位或（OR）。注意：这里的 `xor` 名字虽与异或相同，实际做的是「或」运算。`目标(each) = 源(each) | 值`（不写「源」时 `目标(each) = 目标(each) | 值`）

`xxor 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
按位异或（XOR）。`目标(each) = 源(each) ^ 值`（不写「源」时 `目标(each) = 目标(each) ^ 值`）

`xsl 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
左移。`目标(each) = 源(each) << 值`（不写「源」时 `目标(each) = 目标(each) << 值`）

`xsr 目标[内存/输出] 源?[输入/内存/物流] 值[数值/引用]`
右移。`目标(each) = 源(each) >> 值`（不写「源」时 `目标(each) = 目标(each) >> 值`）


## SIMD 统计

`xmin 目标[引用/输出] 源[输入/内存/物流]`
找出「源」中的最小信号并复制到「目标」。

`xmax 目标[引用/输出] 源[输入/内存/物流]`
找出「源」中的最大信号并复制到「目标」。

`xavg 目标[引用/输出] 源[输入/内存/物流]`
计算「源」中信号的平均值，写入「目标」。

`xmini 目标[引用/输出] 源[输入/内存/物流]`
找出「源」中最小信号的位置，把位置序号写入「目标」。

`xmaxi 目标[引用/输出] 源[输入/内存/物流]`
找出「源」中最大信号的位置，把位置序号写入「目标」。


# 内存

这里解释一下模组的内存机制，以及为什么这样设计。

Factorio 的线缆可以同时承载数百个信号，但这些信号没有任何顺序，下标是随机的。为了让界面好看，GUI 面板会把信号按降序排列（电线杆和 ⓘ 信息提示都是这样）。

原版运算器由游戏内部用 C++ 实现，处理大量信号很快；而用 Lua 处理同等数量的信号会产生很大的开销、性能很差——这一点对所有 Factorio 模组都一样。

为了绕开这个问题，程控运算器用了一个技巧：把程序里的 SIMD 指令`x*`部分编译成由原版运算器组成的隐形电路，再逐行协调执行。这一部分被称为协处理器，性能远好于直接用 Lua 计算。

和始终保留下标的寄存器（用普通变量实现）不同，SIMD 指令使用的内存同样由原版运算器承载。

最重要的一点：

* 修改内存时，必须先对同一信号减去旧值、再加上新值
* 和所有原版运算器操作一样，这样做会打乱信号的顺序


